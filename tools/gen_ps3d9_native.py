#!/usr/bin/env python3
"""gen_ps3d9_native.py <translated glsl dir>: app/shaders_native/ps_{FD5D..,CD0F..}.glsl from app/shaders_native/src/ps3d9_body.glsl.

Each output is its translation's header (bindings, specialisation constants, up to `void main()`), the body (its main()
up to `vec4 r3d_out`), then the translation's tail (alpha test, blend skip, output trim) with its colour variables
renamed to r3d_out. Run on XenosRecomp's output (out/deko3d_shaders/glsl_opt before the native copy, or a backup).
"""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADERS = {"ps_FD5D018F1474A584": 0, "ps_CD0F7080E288829E": 1}
GATHER = int(os.environ.get("R3D_GATHER", "0"))  # two textureGathers for a contiguous footprint (no faster on the console)
MIN = int(os.environ.get("R3D_MIN", "0"))  # measurement only: the vertex colour alone


def main() -> None:
    src = Path(sys.argv[1])
    body = (ROOT / "app/shaders_native/src/ps3d9_body.glsl").read_text()
    for name, kill in SHADERS.items():
        lines = (src / f"{name}.glsl").read_text().splitlines()
        if any("r3d_out" in l for l in lines):
            sys.exit(f"{name}: already the native shader; pass the translation")
        m = lines.index("void main()")
        t = next(i for i, l in enumerate(lines) if "uintBitsToFloat(g_UboShared.v[34u].z)" in l)
        tail = "\n".join(lines[t:])
        alpha = re.search(r"\((_\d+) < _\d+\)", lines[t + 1]).group(1)
        rgb = re.search(r"isnan\((_\d+)\.xyz\)", tail).group(1)
        out = re.search(r"out_var_SV_Target0 = mix\((_\d+),", tail).group(1)
        for var, new in ((out, "r3d_out"), (rgb, "r3d_out"), (alpha, "r3d_out.w")):
            tail = re.sub(rf"\b{var}\b", new, tail)
        head = lines[:2] + [f"// scudrace-nx: native ps3d9 (R3D_KILL {kill}); generated by tools/gen_ps3d9_native.py from "
                            "app/shaders_native/src/ps3d9_body.glsl", f"#define R3D_KILL {kill}", f"#define R3D_GATHER {GATHER}", f"#define R3D_MIN {MIN}"] + lines[2:m]
        text = "\n".join(head) + "\n" + body.rstrip() + "\n" + tail + "\n"
        (ROOT / f"app/shaders_native/{name}.glsl").write_text(text)
        print(f"{name}: alpha {alpha}, rgb {rgb}, out {out} -> r3d_out")


if __name__ == "__main__":
    main()
